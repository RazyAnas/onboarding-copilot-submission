import { chromium } from "./node/node_modules/playwright-core/index.mjs";
import fs from "node:fs";
const b = await chromium.launch({ channel: "chrome", headless: true });
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
const p = await ctx.newPage();
const reqs = []; const t0 = { v: 0 };
p.on("request", r => { if (r.url().includes(":8787")) reqs.push({ t: Date.now(), method: r.method(), path: new URL(r.url()).pathname, bytes: (r.postData() || "").length, url: r.url() }); });
p.on("response", async r => { const q = reqs.find(x => x.url === r.url() && !x.done); if (q) { q.done = true; q.ms = Date.now() - q.t; q.status = r.status(); } });
await p.goto("http://localhost:5181/#/dashboard", { waitUntil: "load" }); await p.waitForTimeout(1500);
const startN = reqs.length; const mark = () => reqs.length;
const log = [];
const step = async (name, fn) => { const n0 = mark(); const t = Date.now(); await fn(); await p.waitForTimeout(700); log.push({ step: name, calls: reqs.slice(n0).map(r => r.method + " " + r.path), ms: Date.now() - t }); };
await p.locator("text=Start guide").click(); await p.waitForTimeout(1200);
log.push({ step: "start", calls: reqs.slice(startN).map(r => r.method + " " + r.path) });
const sp = async () => await p.evaluate(() => { const h = document.querySelector("[data-cp-root], #copilot-root, [id*=copilot]"); return h ? h.id : null; });
await step("open-settings", async () => { await p.locator("aside >> text=Settings").click(); });
await step("click-invite", async () => { await p.locator('[data-testid="members-invite"]').click(); });
await step("fill-email", async () => { await p.locator('[data-testid="invite-email"]').fill("a@b.co"); });
await step("send-invite", async () => { await p.locator('[data-testid="send-invite"]').click(); });
await p.waitForTimeout(1500);
const total = reqs.filter(r => r.path.startsWith("/v1")).length;
const byPath = {}; reqs.forEach(r => { const k = r.method + " " + r.path.replace(/s_[\w-]+/, ":id"); byPath[k] = (byPath[k] || 0) + 1; });
console.log(JSON.stringify({ log, byPath, total, details: reqs.map(r => ({ p: r.path.replace(/s_[\w-]+/, ":id"), m: r.method, bytes: r.bytes, ms: r.ms })) }, null, 1));
fs.writeFileSync("../results/live_walk.json", JSON.stringify({ log, byPath, total, reqs }, null, 1));
await p.screenshot({ path: "../results/live_end.png" });
await b.close();
